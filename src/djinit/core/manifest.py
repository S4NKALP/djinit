"""
Project manifest management for djinit.
Handles reading and writing .djinit.toml and backward-compatible .djinit (JSON).
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

try:
    import tomllib
except ImportError:  # pragma: no cover
    import tomli as tomllib  # type: ignore

CURRENT_SCHEMA_VERSION = 1

VALID_STRUCTURES = frozenset(
    {
        "standard",
        "predefined",
        "unified",
        "single",
        "modular_monolith",
        "service_layer",
        "fullstack_htmx",
        "lightweight",
        "ddd",
        "clean_architecture",
        "multi_tenant",
    }
)

# Friendly mapping for legacy or alternative names
STRUCTURE_ALIASES = {
    "modular-monolith": "modular_monolith",
    "service-layer": "service_layer",
    "fullstack-htmx": "fullstack_htmx",
    "full_stack_htmx": "fullstack_htmx",
    "domain-driven-design": "ddd",
    "domain_driven_design": "ddd",
    "clean-architecture": "clean_architecture",
    "multi-tenant": "multi_tenant",
    "single-folder": "single",
}


@dataclass
class ProjectSection:
    name: str
    structure: str = "standard"
    schema_version: int = CURRENT_SCHEMA_VERSION
    apps_dir: str | None = None
    module_name: str | None = None

    def __post_init__(self):
        canonical = STRUCTURE_ALIASES.get(self.structure, self.structure)
        if canonical not in VALID_STRUCTURES:
            raise ValueError(f"Unknown structure: '{self.structure}'. Valid choices: {sorted(VALID_STRUCTURES)}")
        self.structure = canonical


@dataclass
class FeaturesSection:
    drf: bool = True
    jwt: bool = True
    htmx: bool = False
    tailwind: bool = False
    alpine: bool = False
    vite: bool = False


@dataclass
class DatabaseSection:
    engine: str = "sqlite3"
    use_database_url: bool = False


@dataclass
class DeploymentSection:
    target: str = "docker"


@dataclass
class ProjectManifest:
    project: ProjectSection
    features: FeaturesSection = field(default_factory=FeaturesSection)
    database: DatabaseSection = field(default_factory=DatabaseSection)
    deployment: DeploymentSection = field(default_factory=DeploymentSection)

    def to_dict(self) -> dict[str, Any]:
        return {
            "project": {
                "name": self.project.name,
                "structure": self.project.structure,
                "schema_version": self.project.schema_version,
                "apps_dir": self.project.apps_dir,
                "module_name": self.project.module_name,
            },
            "features": {
                "drf": self.features.drf,
                "jwt": self.features.jwt,
                "htmx": self.features.htmx,
                "tailwind": self.features.tailwind,
                "alpine": self.features.alpine,
                "vite": self.features.vite,
            },
            "database": {
                "engine": self.database.engine,
                "use_database_url": self.database.use_database_url,
            },
            "deployment": {
                "target": self.deployment.target,
            },
        }

    def to_toml(self) -> str:
        lines: list[str] = [
            "# Generated by djinit",
            "[project]",
            f"name = {json.dumps(self.project.name)}",
            f"structure = {json.dumps(self.project.structure)}",
            f"schema_version = {self.project.schema_version}",
        ]
        if self.project.apps_dir:
            lines.append(f"apps_dir = {json.dumps(self.project.apps_dir)}")
        if self.project.module_name:
            lines.append(f"module_name = {json.dumps(self.project.module_name)}")

        lines.extend(
            [
                "",
                "[features]",
                f"drf = {str(self.features.drf).lower()}",
                f"jwt = {str(self.features.jwt).lower()}",
                f"htmx = {str(self.features.htmx).lower()}",
                f"tailwind = {str(self.features.tailwind).lower()}",
                f"alpine = {str(self.features.alpine).lower()}",
                f"vite = {str(self.features.vite).lower()}",
                "",
                "[database]",
                f"engine = {json.dumps(self.database.engine)}",
                f"use_database_url = {str(self.database.use_database_url).lower()}",
                "",
                "[deployment]",
                f"target = {json.dumps(self.deployment.target)}",
                "",
            ]
        )
        return "\n".join(lines)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> ProjectManifest:
        proj_data = data.get("project", {})
        feat_data = data.get("features", {})
        db_data = data.get("database", {})
        dep_data = data.get("deployment", {})

        return cls(
            project=ProjectSection(
                name=proj_data.get("name", "project"),
                structure=proj_data.get("structure", "standard"),
                schema_version=proj_data.get("schema_version", CURRENT_SCHEMA_VERSION),
                apps_dir=proj_data.get("apps_dir"),
                module_name=proj_data.get("module_name"),
            ),
            features=FeaturesSection(
                drf=feat_data.get("drf", True),
                jwt=feat_data.get("jwt", True),
                htmx=feat_data.get("htmx", False),
                tailwind=feat_data.get("tailwind", False),
                alpine=feat_data.get("alpine", False),
                vite=feat_data.get("vite", False),
            ),
            database=DatabaseSection(
                engine=db_data.get("engine", "sqlite3"),
                use_database_url=db_data.get("use_database_url", False),
            ),
            deployment=DeploymentSection(
                target=dep_data.get("target", "docker"),
            ),
        )

    @classmethod
    def from_toml(cls, toml_str: str) -> ProjectManifest:
        data = tomllib.loads(toml_str)
        return cls.from_dict(data)

    @classmethod
    def from_legacy_djinit_json(cls, json_dict: dict[str, Any]) -> ProjectManifest:
        """Convert old .djinit JSON configuration into a modern ProjectManifest."""
        project_name = json_dict.get("project_name", "project")
        structure = json_dict.get("structure", {})
        apps_cfg = json_dict.get("apps", {})
        settings_cfg = json_dict.get("settings", {})

        if structure.get("predefined"):
            struct_name = "predefined"
            apps_dir = "apps"
            module_name = "config"
        elif structure.get("unified"):
            struct_name = "unified"
            apps_dir = "apps"
            module_name = "core"
        elif structure.get("single"):
            struct_name = "single"
            apps_dir = None
            module_name = project_name
        else:
            struct_name = "standard"
            apps_dir = apps_cfg.get("nested_dir") if apps_cfg.get("nested") else None
            module_name = project_name

        return cls(
            project=ProjectSection(
                name=project_name,
                structure=struct_name,
                apps_dir=apps_dir,
                module_name=module_name,
            ),
            features=FeaturesSection(
                htmx=settings_cfg.get("use_htmx", False),
                tailwind=settings_cfg.get("use_tailwind", False),
                vite=settings_cfg.get("use_vite", False),
            ),
            database=DatabaseSection(
                engine=settings_cfg.get("database_type", "sqlite3"),
                use_database_url=settings_cfg.get("use_database_url", False),
            ),
        )


class ManifestManager:
    """Finds, loads, and writes manifests with fallback support."""

    @staticmethod
    def find_manifest_file(start_dir: str | None = None) -> tuple[str | None, str | None]:
        """Search current and parent dirs for .djinit.toml or .djinit.

        Returns (file_path, type) where type is 'toml' or 'json'.
        """
        if start_dir is None:
            start_dir = os.getcwd()

        curr: Path | None = Path(start_dir).resolve()
        while curr:
            toml_candidate = curr / ".djinit.toml"
            if toml_candidate.is_file():
                return str(toml_candidate), "toml"

            json_candidate = curr / ".djinit"
            if json_candidate.is_file():
                return str(json_candidate), "json"

            parent = curr.parent
            if parent == curr:
                break
            curr = parent

        return None, None

    @classmethod
    def load_manifest(cls, start_dir: str | None = None) -> ProjectManifest | None:
        filepath, filetype = cls.find_manifest_file(start_dir)
        if not filepath:
            return None

        try:
            if filetype == "toml":
                with open(filepath, "rb") as f:
                    data = tomllib.load(f)
                return ProjectManifest.from_dict(data)
            elif filetype == "json":
                with open(filepath, encoding="utf-8") as f:
                    data = json.load(f)
                return ProjectManifest.from_legacy_djinit_json(data)
        except Exception:
            return None

        return None

    @classmethod
    def save_manifest(cls, target_dir: str, manifest: ProjectManifest) -> None:
        """Write .djinit.toml in target_dir."""
        os.makedirs(target_dir, exist_ok=True)
        toml_path = os.path.join(target_dir, ".djinit.toml")
        with open(toml_path, "w", encoding="utf-8") as f:
            f.write(manifest.to_toml())
